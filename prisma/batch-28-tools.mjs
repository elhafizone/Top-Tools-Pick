async function run() {
  const cats = await prisma.category.findMany({ select: { id: true, slug: true } });
  const catMap = Object.fromEntries(cats.map(c => [c.slug, c.id]));
  const existing = await prisma.product.findMany({ select: { slug: true } });
  const existingSlugs = new Set(existing.map(p => p.slug));
  let added = 0, skipped = 0;
  for (const t of tools) {
    if (existingSlugs.has(t.slug)) { skipped++; continue; }
    const catId = catMap[t.cat];
    if (!catId) { console.warn("Unknown category:", t.cat); continue; }
    await prisma.product.create({
      data: {
        name: t.name, slug: t.slug,
        shortDescription: t.short, description: t.desc,
        websiteUrl: t.url, categoryId: catId,
        pricingModel: t.pricing, rating: t.rating,
        editorialScore: t.score, featured: false,
        hasFreePlan: t.free, hasFreeTrial: t.freeTrial,
        bestFor: t.bestFor, notFor: t.notFor,
        pros: JSON.stringify(t.pros), cons: JSON.stringify(t.cons),
        keyFeatures: JSON.stringify(t.keyFeatures), integrations: JSON.stringify(t.integrations),
        verdict: t.verdict, seoTitle: t.seoTitle,
        seoDescription: t.seoDescription,
        logoUrl: t.logo || null, status: "PUBLISHED",
      },
    });
    added++;
  }
  console.log(`\nBatch 28 done! Added: ${added}, Skipped: ${skipped}`);
  await prisma.$disconnect();
}
run().catch(e => { console.error(e); process.exit(1); });
